// 在真实 Vite 页面执行：playwright-cli run-code --filename=frontend/test/browser/fileDetailViewDropdown.js
// 使用确定性 HTTP 夹具验证视图选择，不修改业务文件。
async page => {
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const checkDivider = async menu => {
    const colors = await menu.locator('.ant-dropdown-menu-item-divider').evaluate(el => {
      const line = getComputedStyle(el)
      const background = getComputedStyle(el.parentElement)
      return { height: line.height, line: line.backgroundColor, background: background.backgroundColor }
    })
    const channels = color => color.match(/[\d.]+/g).map(Number)
    const line = channels(colors.line)
    const background = channels(colors.background)
    const difference = Math.max(...line.slice(0, 3).map((value, index) => Math.abs(value - background[index]) * (line[3] ?? 1)))
    check(colors.height === '1px' && difference >= 20, `分割线与菜单背景区分不足：${JSON.stringify(colors)}`)
  }
  const originalViewport = page.viewportSize()
  const originalTheme = await page.evaluate(() => localStorage.getItem('theme'))
  const routeHandler = async route => {
    const path = route.request().url().replace(/^https?:\/\/[^/]+/, '').split('?')[0]
    if (path.endsWith('/basic')) {
      const single = path.includes('/single-file/')
      const empty = path.includes('/empty-file/')
      return route.fulfill({ json: { meta: { file_id: single ? 'single-file' : empty ? 'empty-file' : 'view-file', filename: '视图测试.docx', status: single || empty ? 'uploaded' : 'indexed', has_original_file: !empty, has_parsed_markdown: !single && !empty } } })
    }
    if (path.endsWith('/content')) return route.fulfill({ json: { content: '# 测试内容', lines: [{ id: 'chunk-1', content: '测试内容', chunk_order_index: 0 }] } })
    if (path.endsWith('/download')) return route.fulfill({ contentType: 'application/octet-stream', body: '原文内容' })
    if (path === '/api/workspace/knowledge/file') return route.fulfill({ contentType: 'text/plain', body: '原文预览夹具' })
    return route.fulfill({ json: {} })
  }
  await page.route('**/api/**', routeHandler)
  await page.setViewportSize({ width: 1024, height: 800 })
  await page.evaluate(async () => {
    const main = await (await fetch('/src/app/main.js')).text()
    const { createApp, h, ref } = await import(main.match(/from "([^"]*\/vue\.js[^"']*)"/)[1])
    const { createPinia } = await import(main.match(/from "([^"]*\/pinia\.js[^"']*)"/)[1])
    const { default: FileDetailModal } = await import('/src/modules/knowledge/ui/FileDetailModal.vue')
    const { useThemeStore } = await import('/src/shared/model/theme.js')
    const { configureApiAuth } = await import('/src/apis/auth_context.js')
    const { useUserStore } = await import('/src/modules/identity/model/user.js')
    configureApiAuth({ getToken: () => 'file-view-fixture', isAdmin: () => true })
    const root = document.querySelector('#app').__vue_app__
    const pinia = createPinia()
    const theme = useThemeStore(pinia)
    const host = document.createElement('div')
    host.id = 'file-view-check'
    Object.assign(host.style, { position: 'fixed', top: '24px', left: '24px', width: '800px', height: '600px', zIndex: 1000, fontFamily: 'var(--font-family)' })
    document.body.append(host)
    const originalCreateObjectURL = URL.createObjectURL
    const originalAnchorClick = HTMLAnchorElement.prototype.click
    const blobs = new Map()
    const downloads = []
    URL.createObjectURL = blob => { const url = originalCreateObjectURL(blob); blobs.set(url, blob); return url }
    HTMLAnchorElement.prototype.click = function () {
      if (this.download && blobs.has(this.href)) downloads.push({ filename: this.download, blob: blobs.get(this.href) })
      return originalAnchorClick.call(this)
    }
    const fileId = ref('view-file')
    const open = ref(true)
    const embedded = ref(true)
    const app = createApp({ render: () => h(root._context.components.AConfigProvider, { theme: theme.currentTheme }, () => h(FileDetailModal, { embedded: embedded.value, open: open.value, kbId: 'kb', fileId: fileId.value })) })
    app.use(pinia)
    Object.assign(app._context.components, root._context.components)
    app.mount(host)
    const user = useUserStore(root.config.globalProperties.$pinia)
    window.fileViewCheck = { app, host, theme, fileId, open, embedded, downloads, restoreAuth: () => configureApiAuth({ getToken: () => user.token, isAdmin: () => user.isAdmin, isSuperAdmin: () => user.isSuperAdmin }), restoreDownloads: () => { URL.createObjectURL = originalCreateObjectURL; HTMLAnchorElement.prototype.click = originalAnchorClick } }
  })
  const host = page.locator('#file-view-check')
  try {
    await host.locator('.markdown-content').waitFor()
    for (const mode of ['light', 'dark']) {
      await page.evaluate(mode => window.fileViewCheck.theme.setTheme(mode), mode)
      const trigger = host.getByRole('button', { name: /文件操作，当前视图为/ })
      for (const [name, panel] of [['Markdown 源码', '.document-source'], ['Chunks', '.chunk-browser'], ['源文件', '.source-panel'], ['Markdown 预览', '.markdown-content']]) {
        await trigger.click()
        const viewMenu = page.locator('.knowledge-file-actions:visible').last()
        await viewMenu.getByRole('menuitem', { name, exact: true }).click()
        await host.locator(panel).waitFor()
        await viewMenu.waitFor({ state: 'hidden', timeout: 4000 }).catch(() => { throw new Error('菜单关闭超时：阶段 0') })
        check((await trigger.getAttribute('aria-label')).includes(name), `当前视图未更新：${name}，实际为 ${await trigger.getAttribute("aria-label")}`)
        await page.waitForTimeout(300)
      }
      await trigger.click()
      const selected = page.locator('.knowledge-file-actions:visible .ant-dropdown-menu-item-selected')
      check((await selected.textContent()).trim() === 'Markdown 预览', '菜单未标明当前视图')
      const menu = page.locator('.knowledge-file-actions:visible')
      check(await menu.locator('.ant-dropdown-menu-item-divider').count() === 1, '视图和下载之间缺少分割线')
      await checkDivider(menu)
      check(await menu.getByRole('menuitem', { name: '下载原文' }).isEnabled(), '原文下载不可用')
      check(await menu.getByRole('menuitem', { name: '下载 Markdown' }).isEnabled(), 'Markdown 下载不可用')
      check(await host.getByRole('button', { name: '下载', exact: true }).count() === 0, '存在重复的下载按钮')
      await page.locator('.knowledge-file-actions:visible').evaluate(async el => { await Promise.allSettled(el.getAnimations().map(animation => animation.finished)) })
      await page.screenshot({ path: `/tmp/yuxi-file-view-dropdown-${mode}.png` })
      await trigger.click()
      await host.evaluate(el => { el.style.width = '500px' })
      const compactTrigger = host.getByRole('button', { name: '更多文件操作', exact: true })
      await compactTrigger.click()
      const compact = page.locator('.knowledge-file-actions:visible').last()
      await checkDivider(compact)
      await compact.evaluate(async el => { await Promise.allSettled(el.getAnimations().map(animation => animation.finished)) })
      await page.screenshot({ path: `/tmp/yuxi-file-view-dropdown-compact-${mode}.png` })
      await compactTrigger.click()
      await compact.waitFor({ state: 'hidden', timeout: 4000 })
      await host.evaluate(el => { el.style.width = '800px' })
    }
    await page.evaluate(() => window.fileViewCheck.theme.setTheme('dark'))
    for (const width of [1024, 768]) {
      await page.setViewportSize({ width, height: 800 })
      await host.evaluate((el, viewportWidth) => { el.style.width = `${Math.min(800, viewportWidth - 48)}px` }, width)
      const trigger = host.getByRole('button', { name: /文件操作，当前视图为/ })
      await trigger.click()
      const menu = page.locator('.knowledge-file-actions:visible').last()
      await menu.getByRole('menuitem', { name: 'Chunks', exact: true }).click()
      await menu.waitFor({ state: 'hidden' })
      await host.locator('.chunk-list-item').waitFor()
      const surfaces = await host.evaluate(el => {
        const style = selector => getComputedStyle(el.querySelector(selector))
        const title = style('.modal-title-wrapper')
        const content = style('.file-detail-content')
        const card = style('.chunk-list-item.selected')
        const bounds = el.getBoundingClientRect()
        return { title: title.backgroundColor, content: content.backgroundColor, card: card.backgroundColor, selection: card.boxShadow, sidebarBorderWidth: style('.chunk-sidebar').borderRightWidth, left: bounds.left, right: bounds.right }
      })
      check(surfaces.card !== surfaces.content && surfaces.selection !== 'none' && surfaces.sidebarBorderWidth === '1px', `暗色分块区分不足：${JSON.stringify(surfaces)}`)
      check(surfaces.card !== surfaces.title, `暗色选中分块与标题区分不足：${JSON.stringify(surfaces)}`)
      check(surfaces.left >= 0 && surfaces.right <= width, `文件详情超出视口：${JSON.stringify(surfaces)}`)
      await page.screenshot({ path: `/tmp/yuxi-file-detail-dark-${width}.png` })
    }
    await page.setViewportSize({ width: 1024, height: 800 })
    await host.evaluate(el => { el.style.width = '800px' })
    await page.waitForTimeout(300)
    await host.evaluate(el => { el.style.width = '500px' })
    const more = host.getByRole('button', { name: '更多文件操作', exact: true })
    check(await more.isVisible(), '窄容器没有收纳操作')
    await more.click()
    const compactMenu = page.locator('.knowledge-file-actions:visible').last()
    await compactMenu.getByRole('menuitem', { name: 'Chunks', exact: true }).waitFor()
    check(await compactMenu.locator('.ant-dropdown-menu-item-divider').count() === 1, '紧凑菜单缺少分割线')
    await checkDivider(compactMenu)
    check(await compactMenu.getByRole('menuitem', { name: '下载原文' }).count() === 1, '紧凑菜单下载重复或缺失')
    await compactMenu.getByRole('menuitem', { name: 'Chunks', exact: true }).focus()
    await page.keyboard.press('Escape')
    await compactMenu.waitFor({ state: 'hidden', timeout: 4000 }).catch(() => { throw new Error('菜单关闭超时：阶段 1') })
    check(await more.evaluate(el => document.activeElement === el), '紧凑菜单关闭后未返回焦点')
    await more.click()
    await compactMenu.getByRole('menuitem', { name: 'Chunks', exact: true }).focus()
    await page.keyboard.press('Enter')
    await host.locator('.chunk-browser').waitFor()
    await compactMenu.waitFor({ state: 'hidden', timeout: 4000 }).catch(() => { throw new Error('菜单关闭超时：阶段 2') })
    check(await more.evaluate(el => document.activeElement === el), '紧凑菜单键盘选择后未返回焦点')
    await host.evaluate(el => { el.style.width = '800px' })
    await page.waitForTimeout(300)
    const trigger = host.getByRole('button', { name: /文件操作，当前视图为/ })
    await trigger.click()
    await page.locator('.knowledge-file-actions:visible').first().getByRole('menuitem', { name: '下载 Markdown' }).click()
    await page.waitForFunction(() => window.fileViewCheck.downloads.length === 1)
    const markdownDownload = await page.evaluate(async () => ({ filename: window.fileViewCheck.downloads[0].filename, content: await window.fileViewCheck.downloads[0].blob.text() }))
    check(markdownDownload.filename === '视图测试.md' && markdownDownload.content.includes('测试内容'), 'Markdown 下载内容或文件名不正确')
    await page.locator('.knowledge-file-actions:visible').last().waitFor({ state: 'hidden', timeout: 4000 }).catch(() => { throw new Error('菜单关闭超时：阶段 3') })
    await trigger.click()
    await page.locator('.knowledge-file-actions:visible').first().getByRole('menuitem', { name: '下载原文' }).click()
    await page.waitForFunction(() => window.fileViewCheck.downloads.length === 2)
    const originalDownload = await page.evaluate(async () => ({ filename: window.fileViewCheck.downloads[1].filename, content: await window.fileViewCheck.downloads[1].blob.text() }))
    check(originalDownload.filename === '视图测试.docx' && originalDownload.content === '原文内容', '原文下载内容或文件名不正确')
    await page.locator('.knowledge-file-actions:visible').last().waitFor({ state: 'hidden', timeout: 4000 }).catch(() => { throw new Error('菜单关闭超时：阶段 4') })
    await page.evaluate(() => { window.fileViewCheck.fileId.value = 'single-file' })
    const singleTrigger = host.getByRole('button', { name: '文件操作，当前视图为源文件' })
    await singleTrigger.waitFor()
    await singleTrigger.focus()
    await page.keyboard.press('Enter')
    const singleMenu = page.locator('.knowledge-file-actions:visible').last()
    await singleMenu.getByRole('menuitem', { name: '下载原文' }).waitFor()
    check(await singleMenu.getByRole('menuitem').count() === 3, '单视图菜单应包含一个视图和两个下载选项')
    check(await singleMenu.locator('.ant-dropdown-menu-item-divider').count() === 1, '单视图菜单缺少分割线')
    check(await singleMenu.getByRole('menuitem', { name: '下载 Markdown' }).getAttribute('aria-disabled') === 'true', '没有 Markdown 时下载应禁用')
    await page.keyboard.press('Escape')
    await singleMenu.waitFor({ state: 'hidden', timeout: 4000 }).catch(() => { throw new Error('菜单关闭超时：阶段 5') })
    check(await singleTrigger.evaluate(el => document.activeElement === el), '菜单关闭后未返回焦点')
    await host.evaluate(el => { el.addEventListener('keydown', event => { if (event.key === 'Escape') el.dataset.escapeBubbled = 'true' }, { once: true }) })
    await page.keyboard.press('Escape')
    check(await host.getAttribute('data-escape-bubbled') === 'true', '菜单关闭后 Escape 未传递给外层')
    await page.evaluate(() => { window.fileViewCheck.fileId.value = 'empty-file' })
    const emptyTrigger = host.getByRole('button', { name: '文件操作', exact: true })
    await emptyTrigger.waitFor()
    await emptyTrigger.click()
    const emptyMenu = page.locator('.knowledge-file-actions:visible').last()
    await emptyMenu.getByRole('menuitem', { name: '下载原文' }).waitFor()
    check(await emptyMenu.getByRole('menuitem').count() === 2, '没有预览视图时下载选项应保留')
    check(await emptyMenu.locator('.ant-dropdown-menu-item-divider').count() === 0, '没有视图时不应显示分割线')
    await page.evaluate(() => { window.fileViewCheck.fileId.value = 'view-file' })
    const restoredTrigger = host.getByRole('button', { name: /文件操作，当前视图为/ })
    await restoredTrigger.waitFor()
    await emptyMenu.waitFor({ state: 'hidden' })
    check(await page.locator('.knowledge-file-actions:visible').count() === 0, '切换文件后菜单自动展开')
    await restoredTrigger.click()
    const reopenedMenu = page.locator('.knowledge-file-actions:visible').last()
    await reopenedMenu.getByRole('menuitem', { name: 'Chunks', exact: true }).waitFor()
    await page.evaluate(() => { window.fileViewCheck.open.value = false })
    await reopenedMenu.waitFor({ state: 'hidden' })
    await page.evaluate(() => { window.fileViewCheck.open.value = true })
    await restoredTrigger.waitFor()
    check(await page.locator('.knowledge-file-actions:visible').count() === 0, '重新打开详情后菜单自动展开')
    await restoredTrigger.focus()
    await page.keyboard.press('Enter')
    const keyboardMenu = page.locator('.knowledge-file-actions:visible').last()
    const keyboardItem = keyboardMenu.getByRole('menuitem', { name: 'Chunks', exact: true })
    await keyboardItem.focus()
    await page.keyboard.press('Enter')
    await keyboardMenu.waitFor({ state: 'hidden' })
    check(await restoredTrigger.evaluate(el => document.activeElement === el), '键盘选择后未返回焦点')
    await page.evaluate(() => { window.fileViewCheck.embedded.value = false })
    const modal = page.locator('.file-detail .ant-modal-content:visible')
    await modal.locator('.chunk-list-item.selected').waitFor()
    const modalSurfaces = await modal.evaluate(el => {
      const background = selector => getComputedStyle(el.querySelector(selector)).backgroundColor
      return { title: background('.modal-title-wrapper'), content: background('.file-detail-content'), card: background('.chunk-list-item.selected'), selection: getComputedStyle(el.querySelector('.chunk-list-item.selected')).boxShadow, sidebarBorderWidth: getComputedStyle(el.querySelector('.chunk-sidebar')).borderRightWidth }
    })
    check(modalSurfaces.card !== modalSurfaces.content && modalSurfaces.selection !== 'none' && modalSurfaces.sidebarBorderWidth === '1px', `暗色弹窗分块区分不足：${JSON.stringify(modalSurfaces)}`)
    await page.waitForTimeout(3000)
    for (const width of [1024, 768]) {
      await page.setViewportSize({ width, height: 800 })
      const bounds = await modal.boundingBox()
      check(bounds.x >= 0 && bounds.x + bounds.width <= width, `弹窗超出 ${width}px 视口`)
      await page.screenshot({ path: `/tmp/yuxi-file-modal-dark-${width}.png` })
    }
    return { views: 4, themes: 2, compact: true, single: true, noView: true, downloads: 2, modalWidths: [1024, 768] }
  } finally {
    await page.evaluate(previousTheme => { window.fileViewCheck.theme.setTheme(previousTheme || 'light'); if (previousTheme === null) localStorage.removeItem('theme'); window.fileViewCheck.app.unmount(); window.fileViewCheck.host.remove(); window.fileViewCheck.restoreAuth(); window.fileViewCheck.restoreDownloads(); delete window.fileViewCheck }, originalTheme)
    await page.setViewportSize(originalViewport)
    await page.unroute('**/api/**', routeHandler)
  }
}
