// 启动 fixtures/threadSessionServer.js 和 Vite:5175 后由 playwright-cli 执行。
// 独立真实 SFC 只接收 threadId；事实通过 HTTP/SSE 到达，不调用 runtime。
// prettier-ignore
async page => {
  await page.unrouteAll({ behavior: 'wait' })
  const origin = page.url().split('/').slice(0, 3).join('/')
  const check = (ok, message) => { if (!ok) throw new Error(message) }
  const control = async data => (await page.request.post('http://127.0.0.1:5186/control', { data })).json()
  const waitForCount = async (field, id, expected) => {
    for (let attempt = 0; attempt < 100; attempt++) {
      const counts = await control({})
      if ((counts[field][id] || 0) === expected) return counts
      await page.waitForTimeout(30)
    }
    throw new Error(`${field}.${id} != ${expected}: ${JSON.stringify(await control({}))}`)
  }
  await page.goto('about:blank')
  await control({ reset: true })
  await page.addInitScript(() => localStorage.setItem('user_token', 'reading-user-a'))
  await page.route('**/api/**', route => route.continue({ url: route.request().url().replace(/^https?:\/\/[^/]+/, 'http://127.0.0.1:5186') }))
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.goto(origin + '/test/browser/fixtures/threadSession.html')
  const left = page.locator('[data-view="0"]'), right = page.locator('[data-view="1"]')
  await left.getByText('a 历史', { exact: true }).waitFor()
  await right.getByText('a 历史', { exact: true }).waitFor()
  let counts = await waitForCount('active', 'a', 1)
  check(counts.opened.a === 1, '同 Thread 双实例启动重复 SSE')
  check(counts.requests.filter(path => path.endsWith('/a/items')).length === 1, '同 Thread 首次历史未合并')
  await control({ id: 'a', event: { type: 'agent.session.turn.output_text.delta', item_id: 'a-message', content_index: 0, delta: '，SSE 增量' } })
  await left.getByText('a 历史，SSE 增量', { exact: true }).waitFor()
  await right.getByText('a 历史，SSE 增量', { exact: true }).waitFor()
  await page.evaluate(() => { window.readingFixture.views[0].active = false })
  await page.waitForTimeout(100)
  counts = await waitForCount('active', 'a', 1)
  check(counts.opened.a === 1, '隐藏一个视图改变另一个订阅')
  await page.evaluate(() => { window.readingFixture.views[1].active = false })
  await waitForCount('active', 'a', 1)
  await control({ id: 'a', set: { text: 'a 历史，SSE 增量，隐藏期间增量' }, event: { type: 'agent.session.turn.output_text.delta', item_id: 'a-message', content_index: 0, delta: '，隐藏期间增量' } })
  await page.evaluate(() => { window.readingFixture.views[1].active = true })
  await right.getByText('a 历史，SSE 增量，隐藏期间增量', { exact: true }).waitFor()
  await waitForCount('active', 'a', 1)
  await control({ id: 'a', set: { status: 'completed', text: '最终结果来自持久 result_run' }, event: { type: 'agent.session.turn.completed', turn: { status: 'completed' } } })
  await right.getByText('最终结果来自持久 result_run', { exact: true }).waitFor()
  check(await right.getByText('a 历史，SSE 增量，隐藏期间增量', { exact: true }).count() === 0, '终态仍展示事件前快照')
  await waitForCount('active', 'a', 0)
  await control({ id: 'slow', set: { text: '旧请求不应写入 B', delay: true } })
  await page.evaluate(() => { window.readingFixture.views[0] = { thread: 'slow', active: true } })
  const loading = left.getByRole('status', { name: '正在加载对话' })
  await loading.waitFor()
  for (let i = 0; i < 100 && !(await control({})).requests.some(path => path.endsWith('/slow/items')); i++) await page.waitForTimeout(20)
  await page.evaluate(() => { window.readingFixture.views[0].thread = 'b' })
  await left.getByText('b 历史', { exact: true }).waitFor()
  await loading.waitFor({ state: 'hidden' })
  await control({ id: 'slow', set: { delay: false }, release: true })
  await page.waitForTimeout(100)
  check(await left.getByText('旧请求不应写入 B', { exact: true }).count() === 0, '旧 Thread 迟到结果污染新 Thread')
  check(await right.getByText('最终结果来自持久 result_run', { exact: true }).count() === 1, '另一 Thread 被切换清空')
  await control({ id: 'error', set: { fail: true } })
  await page.evaluate(() => { window.readingFixture.views[0].thread = 'error' })
  await left.getByRole('alert').getByText('对话读取失败，请重试。').waitFor()
  await left.getByRole('button', { name: '重新读取对话' }).click()
  await left.getByText('error 历史', { exact: true }).waitFor()
  await waitForCount('active', 'error', 1)
  // 首读窗口之外的消息必须在暂时隐藏后保留，不能靠重播分页恢复。
  await control({ id: 'history', set: { rows: 650, status: 'completed' } })
  await page.evaluate(() => { window.readingFixture.views[0].thread = 'history' })
  await left.getByText('历史段落 650：', { exact: false }).waitFor()
  await page.waitForTimeout(200)
  check(await left.evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop < 2), '新视图首读未定位底部')
  await left.evaluate(el => { el.scrollTop = 0 })
  await left.getByText('历史段落 100：', { exact: false }).waitFor()
  const anchor = left.getByText('历史段落 100：', { exact: false })
  await anchor.evaluate(el => el.scrollIntoView({ block: 'center' }))
  await page.waitForTimeout(200)
  const top = await anchor.evaluate(el => el.getBoundingClientRect().top)
  await page.evaluate(() => { window.readingFixture.views[0].active = false })
  await page.waitForTimeout(100)
  await page.evaluate(() => { window.readingFixture.views[0].active = true })
  await page.waitForTimeout(500)
  check(await anchor.count() === 1, '隐藏后丢失已分页历史')
  const offset = await anchor.evaluate(el => el.getBoundingClientRect().top) - top
  check(Math.abs(offset) < 2, `隐藏重开阅读位置偏移 ${offset}px`)
  await page.evaluate(() => { window.readingFixture.views[1].thread = 'history' })
  await right.getByText('历史段落 650：', { exact: false }).waitFor()
  await page.waitForTimeout(300)
  check(await right.evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop < 2), '加入已读取Thread的新视图未定位底部')
  check(Math.abs(await anchor.evaluate(el => el.getBoundingClientRect().top) - top) < 2, '第二视图改变第一个阅读位置')
  // 两个视口共享历史，但手动滚动与后续 SSE 增量不互相抢夺位置。
  await right.evaluate(el => { el.scrollTop = 1700 })
  await page.waitForTimeout(100)
  const rightTop = await right.evaluate(el => el.scrollTop)
  await left.evaluate(el => { el.scrollTop += 50 })
  await page.waitForTimeout(100)
  check(await right.evaluate(el => el.scrollTop) === rightTop, '左视口滚动改变右视口')
  await page.evaluate(() => { window.readingFixture.views[0].active = false })
  // 已完成的 Thread 没有活动 SSE；重新打开运行中的长消息 Thread 验证增量。
  await control({ id: 'scroll-live', set: { text: '持续生成：' + '共享事实不改变手动阅读位置。'.repeat(800) } })
  await page.evaluate(() => { window.readingFixture.views[1].thread = 'scroll-live' })
  await right.getByText('持续生成：', { exact: false }).waitFor()
  await waitForCount('active', 'scroll-live', 1)
  await page.waitForFunction(() => { const el = document.querySelector('[data-view="1"]'); return el.scrollHeight - el.clientHeight - el.scrollTop < 2 })
  await page.waitForTimeout(300)
  await right.evaluate(el => { el.scrollTop = 700 })
  await page.waitForTimeout(100)
  await control({ id: 'scroll-live', event: { type: 'agent.session.turn.item.added', item: {
    id: 'live-next', object: 'agent.session.item', type: 'message', role: 'assistant', status: 'in_progress',
    turn_id: 'turn-scroll-live', content: [{ type: 'output_text', text: '新增消息尾部' }],
    yuxi: { message_id: 'live-next', run_id: 'run-scroll-live', created_at: '2026-11-17T02:00:00Z' }
  } } })
  await right.getByText('新增消息尾部', { exact: true }).waitFor()
  check(Math.abs(await right.evaluate(el => el.scrollTop) - 700) < 2, `新消息抢走手动阅读位置：${await right.evaluate(el => el.scrollTop)}`)
  await page.evaluate(() => { window.readingFixture.views[0].active = true; window.readingFixture.views[1].thread = 'history' })
  await right.getByText('历史段落 650：', { exact: false }).waitFor()
  await control({ id: 'identity', set: { text: '旧身份迟到历史', delay: true } })
  await page.evaluate(() => { window.readingFixture.views[0].thread = 'identity' })
  for (let i = 0; i < 100 && !(await control({})).requests.some(path => path.endsWith('/identity/items')); i++) await page.waitForTimeout(20)
  await page.evaluate(() => { window.readingFixture.user.logout() })
  await waitForCount('active', 'error', 0)
  await right.getByText('历史段落 650：', { exact: false }).waitFor({ state: 'hidden' })
  check(await page.getByText('error 历史', { exact: true }).count() === 0, '登出后旧消息仍可见')
  check(await page.getByText('最终结果来自持久 result_run', { exact: true }).count() === 0, '登出后终态仍可见')
  await control({ id: 'identity', set: { text: '新身份的持久历史', delay: false } })
  await page.evaluate(() => { window.readingFixture.user.token = 'reading-user-b' })
  await left.getByText('新身份的持久历史', { exact: true }).waitFor()
  await control({ id: 'identity', release: true })
  await page.waitForTimeout(100)
  check(await left.getByText('旧身份迟到历史', { exact: true }).count() === 0, '旧身份在途结果写入新身份')
  check(await left.getByText('新身份的持久历史', { exact: true }).count() === 1, '旧身份回包覆盖新身份历史')
  counts = await control({})
  check(counts.requests.every(path => path.startsWith('/api/v1/agents/sessions/') || path.startsWith('/api/agent/threads/')), '独立读取依赖了 Agent/目录初始化')
  await page.screenshot({ path: '/tmp/yuxi-independent-thread-session.png' })
  await page.evaluate(() => window.readingFixture.app.unmount())
  await waitForCount('active', 'identity', 0)
  await page.unrouteAll({ behavior: 'wait' })
  return { independent: true, sharedInitialLoadAndSSE: true, liveDeltaDOM: true, hideKeepsPagedHistoryAndScroll: true, newViewStartsAtBottom: true, independentManualScroll: true, newItemPreservesReading: true, releaseAndRestore: true, terminalSnapshotDOM: true, lateThreadIsolation: true, failureRetry: true, logoutAndIdentity: true }
}
