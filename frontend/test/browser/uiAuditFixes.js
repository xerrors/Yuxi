// 已登录的本地页面上验证审查修复；故障只在浏览器 HTTP 边界注入。
// playwright-cli -s=ui-fixes run-code --filename=frontend/test/browser/uiAuditFixes.js
async (page) => {
  const origin = page.url().split('/').slice(0, 3).join('/')
  const check = (value, message) => { if (!value) throw new Error(message) }
  const evidence = '/tmp/yuxi-ui-fixes-evidence'
  const result = []
  const theme = async (mode) => page.evaluate(async (value) => {
    const { useThemeStore } = await import('/src/shared/model/theme.js')
    useThemeStore().setTheme(value)
  }, mode)
  const shot = async (name, locator = page.locator('#app-router-view')) => locator.screenshot({ path: `${evidence}/${name}.png` })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`${origin}/extensions?tab=mcp`)
  await page.locator('.info-card-name').first().waitFor()
  let mode = 'slow', release
  await page.route('**/api/system/mcp-servers', async (route) => {
    if (mode === 'slow') await new Promise((resolve) => { release = resolve })
    if (mode === 'error') return route.abort('failed')
    if (mode === 'empty') return route.fulfill({ json: { success: true, data: [] } })
    return route.continue()
  })
  await page.getByRole('button', { name: '刷新连接器', exact: true }).click()
  await page.getByRole('status').filter({ hasText: '正在加载连接器' }).waitFor()
  check(await page.getByText('暂无连接器，点击上方按钮添加', { exact: true }).count() === 0, '加载中错误显示空状态')
  const bar = page.locator('.page-header-loading-bar')
  const before = await bar.evaluate((node) => ({ left: node.getBoundingClientRect().left, width: node.getBoundingClientRect().width, opacity: getComputedStyle(node).opacity }))
  await page.waitForTimeout(400) // 采样同一加载周期，检查动效没有位移。
  const after = await bar.evaluate((node) => ({ left: node.getBoundingClientRect().left, width: node.getBoundingClientRect().width, opacity: getComputedStyle(node).opacity }))
  check(before.left === after.left && before.width === after.width, '加载条仍产生位移')
  check(before.opacity !== after.opacity, '加载动效被移除')
  await shot('mcp-loading-light')
  mode = 'error'; release()
  await page.locator('.mcp-cards-page [role="alert"]').waitFor()
  check(await page.locator('.mcp-cards-page .ant-empty').count() === 0, '失败被显示为空列表')
  await shot('mcp-error-light')
  await theme('dark'); await page.setViewportSize({ width: 768, height: 900 })
  await shot('mcp-error-dark-768')
  mode = 'empty'
  await page.getByRole('button', { name: /重\s*试/ }).click()
  await page.getByText('暂无连接器，点击上方按钮添加', { exact: true }).waitFor()
  mode = 'ready'
  await page.getByRole('button', { name: '刷新连接器', exact: true }).click()
  await page.locator('.info-card-name').first().waitFor()
  await page.unroute('**/api/system/mcp-servers')
  result.push('MCP loading/error/empty/recovery; animated opacity without displacement; light/dark/768')

  await theme('light'); await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`${origin}/extensions?tab=knowledge`)
  await page.locator('.info-card-name').first().waitFor()
  const search = page.getByPlaceholder('搜索知识库...')
  await search.fill('__ui_audit_no_match__')
  await page.getByText('未找到匹配的知识库', { exact: true }).waitFor()
  await shot('knowledge-no-match')
  await page.getByRole('button', { name: '清除筛选', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.info-card-name'))
  check(await search.inputValue() === '', '清除筛选未清空搜索')
  check(await page.getByRole('combobox', { name: '知识库类型', exact: true }).count() === 1, '知识库筛选无名称')
  const title = await page.locator('.info-card-name:not(:disabled)').first().innerText()
  await search.fill(title)
  await page.waitForFunction(() => location.search.includes('kb_search='))
  await page.locator('.info-card-name:not(:disabled)').first().focus()
  await page.keyboard.press('Enter')
  await page.waitForURL('**/extensions/knowledge-bases/**')
  await page.goBack()
  await search.waitFor()
  check(await search.inputValue() === title, '返回列表后查询丢失')
  await page.getByRole('button', { name: '新建知识库', exact: true }).click()
  await page.locator('#knowledge-base-create-name').fill('临时检查草稿')
  await page.getByRole('button', { name: /下一步/ }).click()
  await page.keyboard.press('Escape')
  await page.getByText('放弃创建知识库？', { exact: true }).waitFor()
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await page.locator('.ant-modal-confirm').waitFor({ state: 'detached' })
  check(await page.locator('.knowledge-base-create-modal:visible, .ant-modal-content:visible').count() > 0, '取消放弃后创建弹窗消失')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '放弃创建', exact: true }).click()
  await page.locator('.ant-modal-confirm').waitFor({ state: 'detached' })
  result.push('Knowledge empty search, reset, labelled filter, keyboard open, back retains query, draft protection')

  await page.goto(`${origin}/extensions?tab=tools`)
  await page.getByRole('combobox', { name: '工具分类', exact: true }).waitFor()
  const agentsResponse = page.waitForResponse((response) => response.url().endsWith('/api/agent') && response.request().method() === 'GET')
  await page.goto(`${origin}/agent-manage`)
  const { agents } = await (await agentsResponse).json()
  await page.locator('.agent-card').first().waitFor()
  check(await page.locator('.agent-card .info-card-subtitle').count() === 0, '内部ID仍占用副标题')
  const firstCard = page.locator('.agent-card').first()
  const agentName = await firstCard.locator('.info-card-name').innerText()
  const more = firstCard.getByRole('button', { name: '更多操作', exact: true })
  await more.focus()
  await page.keyboard.press('Enter')
  await page.getByRole('menuitem', { name: '复制 ID', exact: true }).waitFor()
  await page.waitForFunction(() => document.activeElement?.getAttribute('role') === 'menuitem')
  check(await page.getByRole('menuitem', { name: '复制 ID', exact: true }).evaluate((node) => node === document.activeElement), '键盘打开未聚焦首个菜单项')
  await shot('card-menu-keyboard', page.locator('.ant-dropdown:visible'))
  await page.keyboard.press('ArrowDown')
  check(await page.getByRole('menuitem', { name: '编辑智能体', exact: true }).evaluate((node) => node === document.activeElement), '方向键未切换菜单项')
  await page.keyboard.press('Escape')
  check(await more.evaluate((node) => node === document.activeElement && node.getAttribute('aria-expanded') === 'false'), '关闭菜单没有归还焦点')
  await page.keyboard.press('ArrowDown')
  await page.waitForFunction(() => document.activeElement?.getAttribute('role') === 'menuitem')
  await page.keyboard.press('Tab')
  check(await more.getAttribute('aria-expanded') === 'false', 'Tab 离开后菜单未关闭')
  await more.focus()
  await page.keyboard.press(' ')
  await page.waitForFunction(() => document.activeElement?.getAttribute('role') === 'menuitem')
  await page.evaluate(() => {
    window.__uiAuditOriginalCopy = navigator.clipboard.writeText
    window.__uiAuditCopies = []
    navigator.clipboard.writeText = async (value) => { window.__uiAuditCopies.push(value) }
  })
  try {
    await page.keyboard.press('Enter')
    await page.waitForFunction(() => window.__uiAuditCopies.length > 0)
    const copies = await page.evaluate(() => window.__uiAuditCopies)
    check(copies.length === 1 && agents.some((agent) => agent.name === agentName && agent.agent_id === copies[0]), '键盘复制未写入对应 ID 或重复触发')
    check(await more.getAttribute('aria-expanded') === 'false', '执行操作后菜单未关闭')
    check(await page.locator('.ant-modal-content:visible').count() === 0, '菜单操作误触发卡片编辑')
  } finally {
    await page.evaluate(() => {
      navigator.clipboard.writeText = window.__uiAuditOriginalCopy
      delete window.__uiAuditOriginalCopy
      delete window.__uiAuditCopies
    })
  }
  await page.getByRole('button', { name: '新增智能体', exact: true }).click()
  const name = page.locator('#agent-profile-name')
  await name.fill('临时检查草稿')
  await page.keyboard.press('Escape')
  await page.getByText('放弃创建智能体？', { exact: true }).waitFor()
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await page.locator('.ant-modal-confirm').waitFor({ state: 'detached' })
  check(await name.inputValue() === '临时检查草稿', '取消放弃后智能体草稿丢失')
  await shot('agent-draft-retained', page.locator('.ant-modal-content:visible'))
  await page.getByRole('button', { name: '关闭创建弹窗', exact: true }).click()
  await page.getByRole('button', { name: '放弃创建', exact: true }).click()
  await name.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '新增智能体', exact: true }).click()
  await name.waitFor()
  await page.keyboard.press('Escape')
  await name.waitFor({ state: 'hidden' })
  check(await page.locator('.ant-modal-confirm').count() === 0, '未修改表单仍要求放弃确认')
  result.push('Agent description priority, keyboard menu/one ID copy/Escape/Tab, draft cancel/discard, unchanged close')

  await page.goto(`${origin}/workspace`)
  const trigger = page.getByRole('button', { name: '搜索个人空间文件', exact: true })
  await trigger.focus(); await page.keyboard.press('Enter')
  await page.locator('.global-search-input').fill('__ui_audit_no_match__')
  await page.locator('.global-search-close').focus()
  await page.keyboard.press('Enter')
  await page.locator('.global-search-modal').waitFor({ state: 'hidden' })
  check(await trigger.evaluate((node) => document.activeElement === node), '搜索关闭后未恢复焦点')
  await trigger.focus(); await page.keyboard.press('Enter')
  const input = page.locator('.global-search-input')
  await input.waitFor()
  await input.focus()
  await page.keyboard.press('Shift+Tab')
  for (let i = 0; i < 8; i++) {
    check(await page.evaluate(() => !!document.activeElement?.closest('.global-search-modal')), 'Tab 焦点逃出搜索弹窗')
    await page.keyboard.press('Tab')
  }
  check(await page.locator('#app').evaluate((node) => node.inert), '搜索打开时背景未隔离')
  await page.keyboard.press('Escape')
  await page.locator('.global-search-modal').waitFor({ state: 'hidden' })
  check(!await page.locator('#app').evaluate((node) => node.inert), '搜索关闭后背景仍被隔离')
  result.push('Search Enter closes, Tab/Shift+Tab remain inside, Escape and focus restoration')

  await page.locator('.user-info-dropdown').click()
  await page.getByText('设置', { exact: true }).click()
  const settings = page.locator('.settings-container')
  await settings.waitFor()
  check(await page.locator('.settings-sider-nav .sider-item').evaluateAll((nodes) => nodes.every((node) => node.tagName === 'BUTTON')), '设置导航存在不可聚焦入口')
  const web = page.locator('.settings-sider-nav').getByRole('button', { name: '网络搜索', exact: true })
  await web.focus(); await page.keyboard.press('Enter')
  await page.locator('.web-settings').waitFor()
  check(await web.getAttribute('aria-pressed') === 'true', '导航没有选中语义')
  await shot('settings-keyboard-light', settings)
  await page.getByRole('button', { name: '关闭设置', exact: true }).click()
  result.push('Settings native keyboard navigation and selected state; no resource writes')
  return result
}
